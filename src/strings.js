/** Sistem diline (örn. "de-DE") en yakın desteklenen dili verir; yoksa İngilizce. */
function resolveLang(locale) {
  const code = String(locale || '').slice(0, 2).toLowerCase();
  return SUPPORTED_LANGS.includes(code) ? code : 'en';
}

/** Metni seçilen dilde döndürür; anahtar yoksa İngilizce, o da yoksa anahtarın kendisi. */
function translate(lang, key, vars = {}) {
  const table = STRINGS[lang] || STRINGS.en;
  let text = table[key] !== undefined ? table[key] : (STRINGS.en[key] || key);
  for (const [name, value] of Object.entries(vars)) {
    text = text.split(`{${name}}`).join(String(value));
  }
  return text;
}

const radynStrings = { SUPPORTED_LANGS, LANG_NAMES, STRINGS, resolveLang, translate };

if (typeof module !== "undefined" && module.exports) module.exports = radynStrings;
if (typeof window !== "undefined") window.RadynI18n = radynStrings;
